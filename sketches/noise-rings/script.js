
import * as THREE from 'three';

/**
 * ============================================================
 * THREE.JS SETUP
 * ============================================================
 */

// Get the HTML canvas where Three.js will render the scene.
const canvas = document.querySelector('canvas.webgl');

// Create the Three.js scene.
// The scene will contain a single fullscreen plane.
const scene = new THREE.Scene();


/**
 * ============================================================
 * SHADER UNIFORMS
 * ============================================================
 *
 * Uniforms are variables shared between JavaScript and GLSL.
 * JavaScript updates their values, and the shaders use them
 * when calculating each frame.
 */

const uniforms = {

    // Elapsed time in seconds.
    // Used to animate the noise and create moving rings.
    iTime: { value: 0 },

    // Canvas resolution in pixels.
    // Used to centre the shader coordinates and preserve
    // the proportions of the effect.
    iResolution: { value: new THREE.Vector3(1, 1, 1) }

};


/**
 * ============================================================
 * VERTEX SHADER
 * ============================================================
 *
 * The vertex shader determines where the vertices of the
 * fullscreen plane appear on the screen.
 *
 * PlaneGeometry(2, 2) already has coordinates covering
 * the entire screen in clip space.
 *
 * No transformations or camera calculations are needed.
 */

const vertexShader = /* glsl */`

    void main() {

        // Send the vertex position directly to clip space.
        gl_Position = vec4(position, 1.0);

    }

`;


/**
 * ============================================================
 * FRAGMENT SHADER
 * Simplex Noise Rings
 * ============================================================
 *
 * The fragment shader calculates the colour of every pixel.
 *
 * It generates a series of circular patterns using 3D
 * simplex noise. The noise distorts the circles, producing
 * irregular rings that animate over time.
 */

const fragmentShader = /* glsl */`

precision highp float;

// Uniforms received from JavaScript.
uniform float iTime;
uniform vec3 iResolution;


// Number of rings generated by the shader.
#define NUM_RINGS 16.0


// Mathematical constants.
const float PI = 3.14159265359;
const float TAU = 6.28318530718;


/**
 * ============================================================
 * 3D RANDOM FUNCTION
 * ============================================================
 *
 * Generates a pseudo-random 3D vector from an input position.
 *
 * The sine and dot product create a deterministic random-like
 * value. The result is used by the simplex noise function.
 */

vec3 random3(vec3 c) {

    float j = 4096.0 * sin(dot(c, vec3(17.0, 59.4, 15.0)));

    vec3 r;

    r.z = fract(512.0 * j);

    j *= 0.125;

    r.x = fract(512.0 * j);

    j *= 0.125;

    r.y = fract(512.0 * j);

    // Centre the random values around zero.
    return r - 0.5;
}


/**
 * ============================================================
 * SIMPLEX NOISE CONSTANTS
 * ============================================================
 *
 * F3 and G3 are constants used to transform coordinates
 * between Cartesian space and the simplex grid.
 *
 * In three dimensions, the simplex grid is based on
 * tetrahedra rather than cubes.
 */

const float F3 = 0.3333333;
const float G3 = 0.1666667;


/**
 * ============================================================
 * 3D SIMPLEX NOISE
 * ============================================================
 *
 * Produces smooth, continuous noise from a 3D position.
 *
 * Unlike ordinary random values, simplex noise changes
 * smoothly as the input position moves.
 *
 * This makes it useful for creating organic distortions
 * and animated patterns.
 */

float simplex3d(vec3 p) {

    // --------------------------------------------------------
    // 1. Find the current simplex cell.
    // --------------------------------------------------------

    // Determine the integer coordinates of the cell.
    vec3 s = floor(p + dot(p, vec3(F3)));

    // Position relative to the cell origin.
    vec3 x = p - s + dot(s, vec3(G3));


    // --------------------------------------------------------
    // 2. Determine the neighbouring simplex corners.
    // --------------------------------------------------------

    // Compare the components to determine their ordering.
    vec3 e = step(vec3(0.0), x - x.yzx);

    // First and second neighbouring corners.
    vec3 i1 = e * (1.0 - e.zxy);

    vec3 i2 = 1.0 - e.zxy * (1.0 - e);


    // --------------------------------------------------------
    // 3. Calculate positions relative to each corner.
    // --------------------------------------------------------

    vec3 x1 = x - i1 + G3;

    vec3 x2 = x - i2 + 2.0 * G3;

    vec3 x3 = x - 1.0 + 3.0 * G3;


    // --------------------------------------------------------
    // 4. Calculate the influence of each corner.
    // --------------------------------------------------------

    // Squared distances from the four simplex corners.
    vec4 w;

    vec4 d;

    w.x = dot(x, x);
    w.y = dot(x1, x1);
    w.z = dot(x2, x2);
    w.w = dot(x3, x3);

    // Corners farther than the influence radius contribute
    // nothing to the noise value.
    w = max(0.6 - w, 0.0);


    // --------------------------------------------------------
    // 5. Calculate the random gradient contributions.
    // --------------------------------------------------------

    d.x = dot(random3(s), x);

    d.y = dot(random3(s + i1), x1);

    d.z = dot(random3(s + i2), x2);

    d.w = dot(random3(s + 1.0), x3);


    // --------------------------------------------------------
    // 6. Combine the contributions.
    // --------------------------------------------------------

    // Raise the weights to the fourth power.
    // This creates a smooth falloff towards the cell edges.
    w *= w;
    w *= w;

    // Weight each gradient contribution.
    d *= w;

    // Combine the four contributions into one noise value.
    return dot(d, vec4(52.0));
}


/**
 * ============================================================
 * MAIN FRAGMENT SHADER
 * ============================================================
 *
 * This function is executed for every pixel.
 *
 * It:
 * 1. Converts pixel coordinates into centred UV coordinates.
 * 2. Calculates the current animation time.
 * 3. Generates 16 circular patterns.
 * 4. Distorts each circle using simplex noise.
 * 5. Adds a glow contribution around each ring.
 */

void main() {

    // --------------------------------------------------------
    // 1. Pixel coordinates and UV coordinates.
    // --------------------------------------------------------

    // Current pixel position in screen coordinates.
    vec2 fragCoord = gl_FragCoord.xy;

    // Convert pixel coordinates into centred coordinates.
    //
    // Dividing by the screen height keeps the proportions
    // consistent when the canvas is resized.
    vec2 uv = (fragCoord - 0.5 * iResolution.xy) / iResolution.y;


    // Start with a black pixel.
    vec3 col = vec3(0.0);


    // --------------------------------------------------------
    // 2. Animation time.
    // --------------------------------------------------------

    // A repeating time parameter between 0 and 1.
    // The multiplication controls the animation speed.
    float tt = fract(0.3 * iTime);


    // --------------------------------------------------------
    // 3. Generate the noise rings.
    // --------------------------------------------------------

    // Each iteration creates one circular pattern.
    for (float i = 1.0; i <= NUM_RINGS; i++) {


        // ----------------------------------------------------
        // 4. Calculate the angle around the centre.
        // ----------------------------------------------------

        // atan returns the angle of the current UV position.
        // Adding PI shifts the angle into the range [0, 2PI].
        float a = atan(uv.y, uv.x) + PI;


        // Radius used when sampling the noise function.
        float rad = 0.2;


        // ----------------------------------------------------
        // 5. Embedded simplex noise.
        // ----------------------------------------------------

        // Sample 3D simplex noise using the angular position.
        // The ring index provides a different noise pattern
        // for each ring.
        float embeddedNoise = simplex3d(
            vec3(sin(a), cos(a), i)
        );


        // ----------------------------------------------------
        // 6. Calculate horizontal noise displacement.
        // ----------------------------------------------------

        // The sine and cosine terms create a circular path
        // through noise space.
        //
        // The animated time parameter moves the sampling
        // position, making the distortion change over time.
        float nx = 0.12 * simplex3d(
            vec3(
                (10.0 * i) + rad * sin(TAU * tt - 5.0 * a),
                (10.0 * i) + rad * cos(TAU * tt - 5.0 * a),
                embeddedNoise
            )
        );


        // ----------------------------------------------------
        // 7. Calculate vertical noise displacement.
        // ----------------------------------------------------

        // A second noise sample creates an independent
        // displacement in the vertical direction.
        float ny = 0.12 * simplex3d(
            vec3(
                (2.0 * i) + rad * sin(TAU * tt - 5.0 * a),
                (2.0 * i) + rad * cos(TAU * tt - 5.0 * a),
                embeddedNoise
            )
        );


        // ----------------------------------------------------
        // 8. Calculate the dampening factor.
        // ----------------------------------------------------

        // Distance from the UV position to the point (-0.4, 0).
        //
        // Squaring this value later makes the displacement
        // increase with distance from this reference point.
        float d = length(uv - vec2(-0.4));


        // ----------------------------------------------------
        // 9. Calculate the distorted circle.
        // ----------------------------------------------------

        // Start with a circle of radius 0.37.
        //
        // The noise values nx and ny shift its centre.
        // The dampening factor controls the strength of
        // this displacement.
        //
        // abs() gives the absolute distance from the circle.
        // This acts like a simple distance field for the ring.
        float circSDF = abs(
            length(uv - vec2(nx * d * d, ny * d * d)) - 0.37
        );


        // ----------------------------------------------------
        // 10. Add the glow effect.
        // ----------------------------------------------------

        // The glow becomes brighter as circSDF approaches zero.
        //
        // The small minimum value prevents division by zero.
        // Contributions from all rings are accumulated.
        col += d * 0.0008 / max(abs(circSDF), 0.00001);

    }


    // --------------------------------------------------------
    // 11. Final pixel colour.
    // --------------------------------------------------------

    // Output the accumulated colour with full opacity.
    gl_FragColor = vec4(col, 1.0);

}

`;


/**
 * ============================================================
 * SHADER MATERIAL
 * ============================================================
 *
 * ShaderMaterial connects the GLSL vertex and fragment shaders
 * to the Three.js rendering pipeline.
 */

const geometry = new THREE.PlaneGeometry(2, 2);

// Create a material using our custom shaders.
const material = new THREE.ShaderMaterial({

    // Pass the JavaScript uniforms to GLSL.
    uniforms,

    // Vertex and fragment shader source code.
    vertexShader,
    fragmentShader,

    // The fullscreen plane does not need depth testing.
    depthTest: false,

    // It also does not need to write to the depth buffer.
    depthWrite: false

});

// Create a mesh from the plane and shader material.
const mesh = new THREE.Mesh(geometry, material);

// Add the fullscreen mesh to the scene.
scene.add(mesh);


/**
 * ============================================================
 * WEBGL RENDERER
 * ============================================================
 *
 * The renderer uses WebGL to draw the scene on the HTML canvas.
 */

const renderer = new THREE.WebGLRenderer({

    canvas,

    // Enable antialiasing to smooth polygon edges.
    antialias: true

});

// Set the background colour to opaque black.
renderer.setClearColor(0x000000, 1);


/**
 * ============================================================
 * RESPONSIVE CANVAS SIZE
 * ============================================================
 *
 * Update the renderer and shader resolution whenever
 * the browser window changes size.
 */

const updateSize = () => {

    const width = window.innerWidth;
    const height = window.innerHeight;

    // Limit pixel ratio to 2 to avoid excessive GPU workload
    // on devices with very high-density screens.
    const pixelRatio = Math.min(window.devicePixelRatio, 2);

    // Set the renderer's pixel ratio and dimensions.
    renderer.setPixelRatio(pixelRatio);
    renderer.setSize(width, height);

    // Update the resolution uniform.
    // The shader uses this value to calculate UV coordinates.
    uniforms.iResolution.value.set(
        width * pixelRatio,
        height * pixelRatio,
        1
    );

};

// Listen for browser window resizing.
window.addEventListener('resize', updateSize);

// Set the initial canvas dimensions.
updateSize();


/**
 * ============================================================
 * ANIMATION LOOP
 * ============================================================
 *
 * Continuously update the time uniform and render the scene.
 */

const timer = new THREE.Timer();

// A basic camera is sufficient because the vertex shader
// directly positions the plane in clip space.
const camera = new THREE.Camera();


const tick = () => {

    // Update the timer.
    timer.update();

    // Pass elapsed time to the fragment shader.
    // This drives the movement of the simplex noise.
    uniforms.iTime.value = timer.getElapsed();

    // Render the scene using the custom shader.
    renderer.render(scene, camera);

    // Request the next animation frame.
    requestAnimationFrame(tick);

};

// Start the animation.
tick();
